# Порядок показа: перемешан один раз (одинаково на любом сервере и после перезапуска).
# Число подобрано так, чтобы две мудрые цитаты не шли подряд. Добавили цитату — порядок
# перемешается заново, это не страшно (тест проверит только, что они не слиплись).
_ORDER = list(range(len(QUOTES)))
random.Random(118595).shuffle(_ORDER)


def quote_for(day=None, lang='ru'):
    """Цитата на день: {'kind', 'text', 'author'}; в английской версии сайта — по-английски"""
    day = day or timezone.localdate()
    quote = QUOTES[_ORDER[day.toordinal() % len(QUOTES)]]
    if lang == 'en':
        return {'kind': quote.kind, 'text': quote.en, 'author': quote.en_author}
    return {'kind': quote.kind, 'text': quote.ru, 'author': quote.ru_author}
